#!/usr/bin/env node
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { atomicWrite, PROJECT_ROOT } from '../lib/core.mjs';

export const SOURCE_LEDGER_JSON_PATH = 'references/source-ledger.json';
export const SOURCE_LEDGER_MARKDOWN_PATH = 'references/source-ledger.md';

function tableCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', '<br>');
}

export function renderSourceLedger(ledger) {
  if (!ledger || !Array.isArray(ledger.sources)) throw new Error('source ledger must contain a sources array');
  const generated = typeof ledger.generated === 'string' ? ledger.generated : 'unknown';
  const rows = ledger.sources.map((source) => {
    const claims = Array.isArray(source.claims) && source.claims.length > 0
      ? source.claims.map(tableCell).join('<br>')
      : 'None recorded';
    return `| \`${tableCell(source.id)}\` | [${tableCell(source.title)}](${source.url}) | ${tableCell(source.source_type)} | ${tableCell(source.confidence)} | ${tableCell(source.retrieved)} | ${tableCell(source.refresh_due)} | ${claims} |`;
  });
  return `---\ntype: ledger\ntitle: Source Ledger\ndomain: references\nstatus: current\ncreated: ${generated}\nupdated: ${generated}\ntags: ["#domain/references", "#type/ledger", "#confidence/institutional"]\nconfidence: institutional\nrelated: ["[[index]]", "[[references/claim-ledger]]", "[[references/CONFIDENCE_TAGS]]"]\nsource_urls: []\n---\n\n# Source Ledger\n\nThis is a generated, human-readable projection of the machine-readable [source-ledger.json](source-ledger.json). Do not edit this file directly. Regenerate it after changing the JSON source.\n\n- Ledger version: ${tableCell(ledger.version)}\n- Source records: ${ledger.sources.length}\n- Generated field: ${generated}\n\n## Sources\n\n| ID | Source | Type | Confidence | Retrieved | Refresh due | Claims |\n| --- | --- | --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`;
}

export async function generateSourceLedger(root = PROJECT_ROOT) {
  const input = JSON.parse(await readFile(path.join(root, SOURCE_LEDGER_JSON_PATH), 'utf8'));
  await atomicWrite(path.join(root, SOURCE_LEDGER_MARKDOWN_PATH), renderSourceLedger(input));
  return SOURCE_LEDGER_MARKDOWN_PATH;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    process.stdout.write(`${await generateSourceLedger()}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
